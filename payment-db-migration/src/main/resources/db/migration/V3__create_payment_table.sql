CREATE TABLE IF NOT EXISTS PAYMENT (
    ID UUID PRIMARY KEY,
    TRANSACTION_ID VARCHAR(36) NOT NULL,
    SOURCE_ACCOUNT VARCHAR(20) NOT NULL,
    TARGET_ACCOUNT VARCHAR(20) NOT NULL,
    AMOUNT NUMERIC(19, 2) NOT NULL,
    CURRENCY VARCHAR(3) NOT NULL,
    PAYMENT_METHOD VARCHAR(20) NOT NULL,
    EVENT_TIMESTAMP TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_PAYMENT_TRANSACTION_ID UNIQUE (TRANSACTION_ID),
    CONSTRAINT FK_PAYMENT_SOURCE_ACCOUNT FOREIGN KEY (SOURCE_ACCOUNT) REFERENCES ACCOUNT (NUMBER),
    CONSTRAINT FK_PAYMENT_TARGET_ACCOUNT FOREIGN KEY (TARGET_ACCOUNT) REFERENCES ACCOUNT (NUMBER),
    CONSTRAINT CK_PAYMENT_AMOUNT_POSITIVE CHECK (AMOUNT > 0)
);

CREATE INDEX IDX_PAYMENT_SOURCE_ACCOUNT ON PAYMENT(SOURCE_ACCOUNT);
CREATE INDEX IDX_PAYMENT_TARGET_ACCOUNT ON PAYMENT(TARGET_ACCOUNT);
